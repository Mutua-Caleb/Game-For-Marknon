const VOCAB_VAULT_KEY = 'observatory-vocab-vault-v1'
const READING_PROGRESS_KEY = 'observatory-reading-progress-v1'

export function readVocabVault() {
  try {
    const raw = localStorage.getItem(VOCAB_VAULT_KEY)
    const parsed = raw ? JSON.parse(raw) : null
    if (Array.isArray(parsed) && parsed.length > 0) return parsed
  } catch {
    // fallback
  }
  return BRITISH_PREP_VOCAB.slice(0, 6).map(v => ({ ...v, mastered: false }))
}

export function saveVocabVault(items) {
  try {
    localStorage.setItem(VOCAB_VAULT_KEY, JSON.stringify(items))
  } catch {
    // ignore
  }
}

export function addWordToVocabVault(entry) {
  const current = readVocabVault()
  const exists = current.some(w => w.word.toLowerCase() === entry.word.toLowerCase())
  if (exists) return current
  const next = [
    {
      id: entry.id || `vault_${entry.word.toLowerCase()}`,
      word: entry.word,
      pos: entry.pos || 'word',
      phonetic: entry.phonetic || '',
      definition: entry.definition,
      synonyms: entry.synonyms || [],
      antonyms: entry.antonyms || [],
      example: entry.example || '',
      mastered: false
    },
    ...current
  ]
  saveVocabVault(next)
  return next
}

export function readReadingProgress() {
  try {
    const raw = localStorage.getItem(READING_PROGRESS_KEY)
    return raw ? JSON.parse(raw) : {}
  } catch {
    return {}
  }
}

export function saveReadingPassageResult(passageId, { score, total, peelCompleted }) {
  const current = readReadingProgress()
  const prev = current[passageId] || { bestScore: 0, total, peelCompleted: false }
  current[passageId] = {
    bestScore: Math.max(prev.bestScore || 0, score),
    total,
    peelCompleted: Boolean(prev.peelCompleted || peelCompleted),
    lastCompletedAt: Date.now()
  }
  try {
    localStorage.setItem(READING_PROGRESS_KEY, JSON.stringify(current))
  } catch {
    // ignore
  }
  return current
}
